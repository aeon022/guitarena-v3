export const parseGuestbookEntry = (filename: string) => {
  const parts = filename.split('_');
  const dateStr = parts[1]; 
  const nameParts = parts.slice(2, -1); 
  const artistName = nameParts.join(' ').replace(/_u\._/g, ' & ');
  const year = dateStr.split('-')[0];
  
  return {
    filename,
    artistName,
    dateStr,
    year
  };
};
